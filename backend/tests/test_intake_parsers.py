def test_child_over_the_memory_limit_fails_on_linux(monkeypatch: pytest.MonkeyPatch) -> None:
    """The child sets its own limits from the environment the parent gives it."""
    allocate = (
        "from app.modules.intake.adapters.parse_cli import _apply_limits; _apply_limits(); "
        "x = bytearray(512 * 1024 * 1024)"
    )
    monkeypatch.setattr(
        parse_runner, "child_command", lambda path, ext: [sys.executable, "-c", allocate]
    )
    env = parse_runner.child_env(128, 5)
    assert (env["PSA_PARSE_LIMIT_MEMORY_MB"], env["PSA_PARSE_LIMIT_CPU_S"]) == ("128", "5")
    if sys.platform != "linux":
        return  # elsewhere only the wall-clock limit applies
    with pytest.raises(ParseError) as info:
        run_async(run_parse(FIXTURES / "sample.txt", ".txt", timeout_s=30, max_memory_mb=128))
    assert info.value.code is ParseErrorCode.UNREADABLE


def test_child_sees_only_allowlisted_environment(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("PSA_TEST_SECRET_TOKEN", "s3cret-value")
    dump = (
        "import os, sys; sys.stdout.write(repr(dict(os.environ))); sys.stderr.write('parser=env@0')"
    )
    monkeypatch.setattr(
        parse_runner, "child_command", lambda path, ext: [sys.executable, "-c", dump]
    )
    output = run_async(run_parse(FIXTURES / "sample.txt", ".txt", timeout_s=30, max_memory_mb=64))
    assert "PSA_TEST_SECRET_TOKEN" not in output.text
    assert "s3cret-value" not in output.text
    assert "PSA_DATABASE_URL" not in output.text
    assert "PSA_PARSE_LIMIT_MEMORY_MB" in output.text


