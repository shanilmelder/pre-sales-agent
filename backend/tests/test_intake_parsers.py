def test_cancelling_run_parse_kills_the_child(monkeypatch: pytest.MonkeyPatch) -> None:
    started: list[subprocess.Popen[bytes]] = []
    real_popen = subprocess.Popen

    def recording_popen(*args: Any, **kwargs: Any) -> subprocess.Popen[bytes]:
        process: subprocess.Popen[bytes] = real_popen(*args, **kwargs)
        started.append(process)
        return process

    monkeypatch.setattr(parse_runner.subprocess, "Popen", recording_popen)
    monkeypatch.setattr(
        parse_runner,
        "child_command",
        lambda path, ext: [sys.executable, "-c", "import time; time.sleep(60)"],
    )

    async def scenario() -> None:
        task = asyncio.create_task(
            run_parse(FIXTURES / "sample.txt", ".txt", timeout_s=60, max_memory_mb=64)
        )
        while not started:  # noqa: ASYNC110 (Popen runs in this thread; nothing to signal)
            await asyncio.sleep(0.01)
        await asyncio.sleep(0.2)
        task.cancel()
        with pytest.raises(asyncio.CancelledError):
            await task

    run_async(scenario())
    (process,) = started
    assert process.wait(timeout=5) != 0  # killed, not finished
