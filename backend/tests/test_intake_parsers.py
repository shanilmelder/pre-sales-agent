def test_too_much_text_is_too_large_output() -> None:
    assert len(finish("x" * MAX_TEXT_CHARS)) == MAX_TEXT_CHARS
    with pytest.raises(ParseError) as info:
        finish("x" * (MAX_TEXT_CHARS + 1))
    assert info.value.code is ParseErrorCode.TOO_LARGE_OUTPUT


