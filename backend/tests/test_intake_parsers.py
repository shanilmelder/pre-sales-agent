FIXTURES = Path(__file__).resolve().parent / "fixtures" / "sources"


def fixture(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


def expected(name: str) -> str:
    return fixture(f"{name}.expected.txt").decode("utf-8")


def code_of(data: bytes, ext: str) -> ParseErrorCode:
    with pytest.raises(ParseError) as info:
        parse(data, ext)
    return info.value.code


# --- each kind ------------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("name", "parser"),
    [
        ("sample.txt", "text@1"),
        ("sample.eml", "email@1"),
        ("html-only.eml", "email@1"),
        ("sample.vtt", "vtt@1"),
        ("sample.pdf", "pypdf@"),
        ("sample.docx", "docx@1"),
        ("textbox.docx", "docx@1"),
    ],
)
def test_each_kind_parses_to_its_expected_text(name: str, parser: str) -> None:
    result = parse(fixture(name), "." + name.rsplit(".", 1)[1])
    assert result.text == expected(name)
    assert result.parser.startswith(parser)


def test_extension_matching_is_by_lowercase_extension_and_pasted_text_is_txt() -> None:
    assert file_extension("Call.VTT") == ".vtt"
    assert file_extension("Pasted text") == ".txt"


# --- normalising ----------------------------------------------------------------------------


def test_crlf_and_nfd_are_normalised_and_counted_in_code_points() -> None:
    raw = "a\r\nb\rc é".encode()
    result = parse(raw, ".txt")
    assert result.text == "a\nb\nc é"
    assert unicodedata.is_normalized("NFC", result.text)
    assert len(result.text) == 7  # code points: the NFC é is one


def test_normalise_is_idempotent() -> None:
    text = "x\r\n\r\nyé\r"
    assert normalise(normalise(text)) == normalise(text) == "x\n\nyé\n"


def test_txt_drops_a_byte_order_mark_and_keeps_everything_else() -> None:
    assert parse(b"\xef\xbb\xbf  keep  spacing \n", ".txt").text == "  keep  spacing \n"


# --- vtt ------------------------------------------------------------------------------------


def test_vtt_voices_become_speaker_lines_without_timings() -> None:
    data = b"WEBVTT\n\n00:00.000 --> 00:01.000\n<v Ana>Hello\n\n00:01.000 --> 00:02.000\n<v Bo>Hi\n"
    assert parse(data, ".vtt").text == "Ana: Hello\nBo: Hi"


def test_vtt_without_header_is_unreadable() -> None:
    assert code_of(b"00:00.000 --> 00:01.000\nHello\n", ".vtt") is ParseErrorCode.UNREADABLE


def test_vtt_with_no_cues_has_no_text() -> None:
    assert code_of(b"WEBVTT\n\nNOTE nothing said\n", ".vtt") is ParseErrorCode.NO_TEXT


